"""Protected OpenAPI document and interactive API docs.

The API is often exposed through a local tunnel, so the schema and Swagger UI
are behind the same API-key dependency as the data routes. The document is
still generated by FastAPI; this module only adds the authenticated HTTP
surface and pins the OpenAPI version at the application factory.
"""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Depends, Request
from fastapi.openapi.docs import get_redoc_html, get_swagger_ui_html
from fastapi.responses import HTMLResponse

from machina.api.auth import require_api_key

router = APIRouter()


@router.get("/openapi.json", include_in_schema=False, dependencies=[Depends(require_api_key)])
async def openapi_document(request: Request) -> dict[str, Any]:
    """Return the application's OpenAPI 3.2.1 document."""
    return request.app.openapi()


@router.get("/docs", include_in_schema=False, dependencies=[Depends(require_api_key)])
async def swagger_docs() -> HTMLResponse:
    return get_swagger_ui_html(
        openapi_url="/openapi.json",
        title="Machina API docs",
    )


@router.get("/redoc", include_in_schema=False, dependencies=[Depends(require_api_key)])
async def redoc_docs() -> HTMLResponse:
    return get_redoc_html(
        openapi_url="/openapi.json",
        title="Machina API docs",
    )
