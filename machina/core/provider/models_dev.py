"""Bundled models.dev snapshot used by built-in provider listings.

The snapshot is generated by ``tools/sync_models_dev.py`` from an
``anomalyco/models.dev`` checkout. It is deliberately compact: current chat
models, bounded per provider, with context/output limits and reasoning efforts.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

_SNAPSHOT = Path(__file__).with_name("models_dev.json")


@lru_cache(maxsize=1)
def _snapshot() -> dict[str, Any]:
    try:
        data = json.loads(_SNAPSHOT.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def provider_models(provider: str) -> list[dict[str, Any]]:
    providers = _snapshot().get("providers")
    if not isinstance(providers, dict):
        return []
    rows = providers.get(provider)
    if provider == "opencode_session":
        # The local OpenCode session bridge serves the same available model
        # catalog; capability metadata is inherited, tool support is narrowed
        # by the routing inventory (the bridge is text-only).
        rows = providers.get("opencode")
    if provider == "grok":
        rows = providers.get("xai")
        try:
            from machina.security.grok_auth import MODELS

            allowed = set(MODELS)
            rows = [row for row in (rows or []) if row.get("id") in allowed]
        except Exception:
            return []
        rows = [row for row in rows if row.get("id") in allowed]
    if not isinstance(rows, list):
        return []
    result: list[dict[str, Any]] = []
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("id"), str):
            continue
        result.append(
            {
                "id": row["id"],
                "displayName": str(row.get("name") or row["id"]),
                "description": str(row.get("description") or ""),
                "efforts": list(row.get("efforts") or []),
                "contextWindow": int(row.get("context") or 0) or None,
                "maxOutputTokens": int(row.get("output") or 0) or None,
                # Routing metadata is part of the snapshot. Keeping it on the
                # normalized row lets the model router rank capability-fit
                # without importing the private snapshot shape.
                "family": str(row.get("family") or ""),
                "tools": bool(row.get("tools", False)),
                "reasoning": bool(row.get("reasoning", False)),
                "releaseDate": str(row.get("release_date") or ""),
                "source": "models.dev",
            }
        )
    return result
